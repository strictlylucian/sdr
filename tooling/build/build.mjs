import { build, transform } from 'esbuild';
import { mkdir, readFile, writeFile, cp } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { tokenStyles, utilityStyles } from './tokens.mjs';
import { documentationThemeStyles } from './docs-theme.mjs';
import { motifStyles } from './motif.mjs';
import { embeddedFontStyles } from './fonts.mjs';
import { clearBuildOutputs } from './outputs.mjs';

await clearBuildOutputs();
const styles = ['base', 'motif.generated', 'layout', 'forms', 'navigation', 'feedback', 'interactive', 'data'];
await writeFile('packages/core/src/styles/motif.generated.css', await motifStyles());
const generated = tokenStyles() + utilityStyles();
const fonts = await embeddedFontStyles();
await writeFile('packages/core/src/styles/fonts.generated.css', fonts);
await writeFile('packages/core/src/styles/generated.css', generated);
await writeFile('apps/docs/src/styles/theme.generated.css', documentationThemeStyles());
const source = fonts + generated + (await Promise.all(styles.map(name => readFile(`packages/core/src/styles/${name}.css`, 'utf8')))).join('\n');
const css = (await transform(source, { loader: 'css', minify: true, target: 'es2022', legalComments: 'inline' })).code;
for (const directory of ['dist/portable', 'packages/core/dist', 'packages/react/dist', 'apps/docs/public/portable']) await mkdir(directory, { recursive: true });
for (const directory of ['dist/portable', 'packages/core/dist', 'apps/docs/public/portable']) await writeFile(`${directory}/sdr.css`, css);
await build({ entryPoints: ['packages/core/src/portable.ts'], outfile: 'dist/portable/sdr.js', bundle: true, minify: true, format: 'iife', globalName: 'SDR', target: 'es2022', legalComments: 'eof' });
await cp('dist/portable/sdr.js', 'apps/docs/public/portable/sdr.js');
await cp('dist/portable/sdr.js', 'packages/core/dist/sdr.js');
await build({ entryPoints: ['apps/docs/src/demo/portable-demo.js'], outfile: 'apps/docs/public/portable-demo.js', bundle: true, minify: true, format: 'iife', target: 'es2022' });
await build({ entryPoints: ['packages/core/src/index.ts'], outfile: 'packages/core/dist/index.js', bundle: true, format: 'esm', minify: true, target: 'es2022' });
await build({ entryPoints: ['packages/react/src/index.ts'], outfile: 'packages/react/dist/index.js', bundle: true, format: 'esm', banner: { js: '"use client";' }, minify: true, target: 'es2022', external: ['react', 'react-dom', 'react/jsx-runtime'] });
execFileSync(process.execPath, ['node_modules/typescript/bin/tsc', '-p', 'tsconfig.build.json'], { stdio: 'inherit' });
await cp('dist/types/core/src', 'packages/core/dist', { recursive: true });
await cp('dist/types/react/src', 'packages/react/dist', { recursive: true });
for (const name of ['core', 'react']) await cp('LICENSE', `packages/${name}/LICENSE`);
await cp('packages/core/assets/inter/LICENSE.txt', 'packages/core/dist/INTER-LICENSE.txt');
await cp('catalog/motif-provenance.json', 'packages/core/dist/MOTIF-PROVENANCE.json');
console.log('Built React, core and exactly two portable runtime files.');
